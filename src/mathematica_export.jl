using DynamicPolynomials, Dates

mathematica_number(c::Rational) = "(" * string(numerator(c)) * "/" * string(denominator(c)) * ")"
mathematica_number(c::Integer) = string(c)
mathematica_number(c) = "(" * string(c) * ")"

# Exact serialization of a DynamicPolynomials polynomial into a Mathematica
# expression in the variables' print names (x, y).
function mathematica_polynomial_string(p, dvars)
    pieces = String[]
    for (c, m) in zip(coefficients(p), monomials(p))
        factors = [mathematica_number(c)]
        for v in dvars
            e = degree(m, v)
            e == 0 && continue
            push!(factors, e == 1 ? string(v) : string(v) * "^" * string(e))
        end
        push!(pieces, join(factors, "*"))
    end
    return join(pieces, " + ")
end

mathematica_rational(r::Rational) = string(numerator(r)) * "/" * string(denominator(r))

# Serializes the rational rectangle produced by certification_box.
function mathematica_box_string(xrational, yrational)
    return "{{" * mathematica_rational(xrational[1]) * ", " * mathematica_rational(xrational[2]) *
           "}, {" * mathematica_rational(yrational[1]) * ", " * mathematica_rational(yrational[2]) * "}}"
end

# entries: ordered (key, mathematica-literal) pairs; string values must arrive
# pre-quoted by the caller.
function write_mathematica_metadata(path, entries)
    open(path, "w") do io
        println(io, "(* Auto-generated by run_full_pipeline.jl on ", now(), " *)")
        println(io, "runData = <|")
        println(io, join(["  \"" * k * "\" -> " * v for (k, v) in entries], ",\n"))
        println(io, "|>;")
    end
    return path
end
